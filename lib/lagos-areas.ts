// ── Helpers (hand-written, below the generated data) ────────────────────────

/** Mirrors InspectionPricing._titleCase: "ikota" → "Ikota", "vi" → "VI". */
export function areaDisplayName(area: string): string {
  return area
    .split(' ')
    .map((w) =>
      ['vi', 'vgc', 'gra', 'bq', 'lasu', 'cms'].includes(w.toLowerCase())
        ? w.toUpperCase()
        : w.charAt(0).toUpperCase() + w.slice(1),
    )
    .join(' ')
}

/** The state an area is in: Obafemi-Owode is Ogun, everything else Lagos. */
export function stateForLga(lga: string): 'Lagos' | 'Ogun' {
  return lga === 'obafemi_owode' ? 'Ogun' : 'Lagos'
}

/** "Ikeja LGA" → "Ikeja", "Obafemi-Owode LGA (Ogun)" → "Obafemi-Owode". */
export function lgaName(lga: string): string {
  return (LGA_LABELS[lga] ?? lga).replace(/\s*\(Ogun\)$/, '').replace(/\s+LGA$/, '')
}

/**
 * Areas grouped by LGA for one state, with config/areas merged over the
 * compiled list exactly as the app does. Unreadable config falls back to it.
 */
export async function areaGroups(
  state: 'Lagos' | 'Ogun',
): Promise<Array<{ lga: string; label: string; areas: string[] }>> {
  const merged: Record<string, string> = { ...AREA_TO_LGA }
  try {
    const { doc, getDoc } = await import('firebase/firestore')
    const { clientDb } = await import('./firebase-client')
    const remote = (await getDoc(doc(clientDb(), 'config', 'areas'))).data()?.areas
    if (remote && typeof remote === 'object') {
      for (const [area, lga] of Object.entries(remote)) {
        if (typeof lga === 'string') merged[area.toLowerCase()] = lga
      }
    }
  } catch {
    // Compiled list only.
  }
  const byLga = new Map<string, string[]>()
  for (const [area, lga] of Object.entries(merged)) {
    if (stateForLga(lga) !== state) continue
    byLga.set(lga, [...(byLga.get(lga) ?? []), area])
  }
  return [...byLga.entries()]
    .map(([lga, areas]) => ({ lga, label: LGA_LABELS[lga] ?? lga, areas: areas.sort() }))
    .sort((a, b) => a.label.localeCompare(b.label))
}
